export function getLocalizedNakshatra(nakshatraVal: number | string, language: LanguageCode): string {
  let index: number = 1;
  if (typeof nakshatraVal === 'number') {
    index = ((nakshatraVal - 1) % 27) + 1;
  } else if (typeof nakshatraVal === 'string') {
    const cleanStr = nakshatraVal.toLowerCase().trim();
    if (NAKSHATRA_NAME_TO_INDEX[cleanStr]) {
      index = NAKSHATRA_NAME_TO_INDEX[cleanStr];
    } else {
      const matchedKey = Object.keys(NAKSHATRA_NAME_TO_INDEX).find(k => cleanStr.includes(k) || k.includes(cleanStr));
      if (matchedKey) {
        index = NAKSHATRA_NAME_TO_INDEX[matchedKey];
      }
    }
  }

  const nakMap = NAKSHATRA_MAP[index] || NAKSHATRA_MAP[1];
  return nakMap[language] || nakMap.hinglish || (typeof nakshatraVal === 'string' ? nakshatraVal : 'Ashwini');
}

